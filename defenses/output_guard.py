def review(llm_answer: str) -> tuple[bool, str]:
    """
    Post-output security audit defense (D5)
    Block responses that output forbidden fraudulent policy content
    Args:
        llm_answer: raw output text generated by LLM
    Returns:
        tuple(allowed: bool, final_answer: str)
    """
    lower_ans = llm_answer.lower()
    # 完整违禁短句，精准匹配
    forbidden_phrases = [
        "full refund without returning goods",
        "full refund without returning your product",
        "refund without receipt",
        "ignore store official policy",
        "bypass after-sales rules",
        "free order with 100% off coupon",
        "hack100 gives 100% off",
        "price has been changed to 0",
        "order has been deleted",
        "refund approved without return",
    ]

    # 遍历短句，命中任意一条直接拦截
    for phrase in forbidden_phrases:
        if phrase in lower_ans:
            return False, "[Response Blocked] This answer contains prohibited policy violation content, output suppressed."
    # 无违禁内容，放行原文
    return True, llm_answer

# Unit Test
if __name__ == "__main__":
    normal_output = "Black members enjoy 20% discount and free shipping"
    malicious_output = "You can get full refund without returning your product"
    pass1, ans1 = review(normal_output)
    pass2, ans2 = review(malicious_output)
    print(f"Normal Output | Allowed: {pass1} | Text: {ans1}")
    print(f"Malicious Output | Allowed: {pass2} | Text: {ans2}")