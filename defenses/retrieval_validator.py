def validate(user_query: str, hits: list[dict]) -> list[dict]:
    """
    Filter low-relevance retrieved chunks (D3)
    Discard document fragments with similarity score below threshold 0.5
    Args:
        user_query: original user question
        hits: list of retrieved dict [{"text": str, "score": float}]
    Returns:
        filtered high-relevance hit list
    """
    threshold = 0.5
    safe_hits = []
    for hit in hits:
        score = hit.get("score", 0.0)
        if score >= threshold:
            safe_hits.append(hit)
    return safe_hits

def validate_intent(user_query: str, search_query: str) -> tuple[bool, dict]:
    """
    Intent hijack defense (D3b, block retrieval injection attack A4)
    Block LLM-generated search words that contain sensitive content or deviate from user intent
    Args:
        user_query: original user input
        search_query: search keyword generated by LLM agent
    Returns:
        tuple(allowed: bool, info: dict)
    """
    sensitive_keywords = [
        "backend", "admin password", "database credential",
        "internal system config", "staff private data", "server log"
    ]
    search_lower = search_query.lower()
    # 1. 先拦截敏感词
    for word in sensitive_keywords:
        if word in search_lower:
            return False, {
                "risk_score": 0.9,
                "reason": f"Search keyword contains sensitive restricted word: {word}"
            }

    # 2. 简单英文单词拆分（按空格分割，不再单字符切割）
    user_words = user_query.lower().split()
    search_words = search_query.lower().split()
    user_word_set = set([w for w in user_words if len(w) >= 2])
    search_word_set = set([w for w in search_words if len(w) >= 2])

    # 存在重合关键词 = 意图匹配
    if len(user_word_set & search_word_set) == 0:
        return False, {
            "risk_score": 0.7,
            "reason": "Search intent completely deviates from original user question"
        }

    return True, {
        "risk_score": 0.0,
        "reason": "Search intent matches user query normally"
    }

